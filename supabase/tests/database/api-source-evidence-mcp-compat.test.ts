import { randomUUID } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { materializeMissingSourceNulls } from '../../functions/mcp/source_evidence_adapter.js';
import { cleanup, content, editorial, save } from './helpers/post-rpc.js';
import { fixture, json, reserve, reserved, row, rpc } from './helpers/trivia-rpc.js';

const nasaPhase = 'https://science.nasa.gov/moon/moon-phases/';
const nasaLight = 'https://science.nasa.gov/moon/moonlight/';
const claims = [
  "The Moon's repeating cycle has eight named phases.",
  'A complete lunar phase cycle from new Moon to new Moon lasts about 29.5 Earth days.',
  "Moonlight is sunlight reflected from the Moon's surface, not light generated by the Moon.",
  "During waxing phases, the fraction of the Moon's sunlit surface visible from Earth increases from night to night.",
  'During the first-quarter phase, the Moon typically appears high in the evening sky.',
  'A full Moon generally rises around local sunset.',
  'During crescent phases, sunlight reflected from Earth can dimly illuminate the darkened Earth-facing part of the Moon, called earthshine.',
];
const copyLines = [
  'The Moon has eight named phases in its repeating cycle.',
  'A new-Moon-to-new-Moon cycle lasts about 29.5 Earth days.',
  'Moonlight is reflected sunlight, not light the Moon creates.',
  'During waxing phases, more sunlit surface becomes visible from Earth.',
  'A first-quarter Moon usually sits high in the evening sky.',
  'A full Moon generally rises around the time of sunset.',
  "Earthshine may dimly light a crescent Moon's darkened nearside.",
];
const sourceWithoutOptionalDates = (position: number) => {
  const url = position === 3 ? nasaLight : nasaPhase;
  return {
    schema_version: 1,
    url,
    canonical_url: url,
    title: position === 3 ? 'Moonlight' : 'Moon Phases',
    publisher: 'NASA',
    tier: 'A',
    source_type: 'official',
    accessed_at: '2026-10-20T10:09:51Z',
    language: 'en-US',
    supports: 'NASA official educational source supports the complete atomic lunar claim.',
    independence_group: 'NASA',
  };
};

describe('CR-047: seven actual MAN-03 source shapes against SQL and isolated post flow', () => {
  it('pinpoints the omitted three keys on every fact, preserves tier pairing and rejects unsafe metadata', () => {
    for (let position = 1; position <= 7; position++) {
      const source = sourceWithoutOptionalDates(position);
      const before = row<{ valid: boolean }>(
        `select internal.is_valid_source_evidence_v2(${json([source])}) valid`,
      );
      expect(before.valid, `facts[${position - 1}].sources[0] omitted keys`).toBe(false);
      const normalized = materializeMissingSourceNulls([{ sources: [source] }])[0]!.sources[0]!;
      expect(
        Object.keys(normalized).filter((key) =>
          ['published_at', 'updated_at', 'as_of'].includes(key),
        ),
      ).toEqual(['published_at', 'updated_at', 'as_of']);
      for (const key of ['published_at', 'updated_at', 'as_of'] as const) {
        expect(normalized[key], `fact position ${position}: ${key}`).toBeNull();
      }
      expect(
        row<{ valid: boolean }>(
          `select internal.is_valid_source_evidence_v2(${json([normalized])}) valid`,
        ).valid,
        `fact position ${position}: completed SQL evidence shape`,
      ).toBe(true);
      expect(
        row<{ valid: boolean }>(
          `select internal.is_valid_source_evidence_v2(${json([{ ...normalized, tier: 'B' }])}) valid`,
        ).valid,
      ).toBe(false);
      expect(
        row<{ valid: boolean }>(
          `select internal.is_valid_source_evidence_v2(${json([{ ...normalized, published_at: 'not-a-date' }])}) valid`,
        ).valid,
      ).toBe(false);
    }
  });

  it('takes owner context through seven-source reservation, draft save, and source/quality readback', () => {
    const f = fixture();
    try {
      const ctx = rpc(
        f,
        `api.get_page_generation_context(1,'${f.workspace}','${f.page}','trivia',10,'nature_science','single_subject_fast','follow',null)`,
      ) as unknown as {
        data: {
          config_public_id: string;
          context_version: { config_updated_at: string };
          config: { fact_count: unknown; text_budget: unknown };
          page: { target_markets: string[] };
          reuse_policy: { scope: string };
        };
      };
      expect(ctx.data.config_public_id).toMatch(/^[0-9a-f-]{36}$/);
      expect(ctx.data.context_version.config_updated_at).toBe(f.configTime);
      const facts = claims.map((claim_text, index) => ({
        position: index + 1,
        candidate: {
          candidate_key: `cr047_moon_${index + 1}`,
          claim_text,
          subject_key: `moon_phase_topic_${index + 1}`,
          relation_key: 'has_named_part_or_property',
          object_key: `distinct_lunar_property_${index + 1}`,
          numbers: [],
          qualifiers: {
            negated: false,
            comparison_direction: 'none',
            scope: `distinct property ${index + 1}`,
          },
          topic_key: 'nature_science',
          normalization_version: 1,
          ontology_version: 1,
        },
        dedup_reviews: [],
        sources: [sourceWithoutOptionalDates(index + 1)],
        freshness_class: 'stable',
        as_of_date: null,
        requested_expires_at: new Date(Date.now() + 86_400_000 * 45).toISOString(),
        risk_class: 'standard',
        verification_note: 'Isolated source metadata contract regression, not production evidence.',
      }));
      const normalized = materializeMissingSourceNulls(facts);
      const token = randomUUID();
      const reservation = rpc(
        f,
        reserve(f, normalized, randomUUID(), token, ctx.data.context_version.config_updated_at),
      );
      const persisted = reserved(reservation);
      expect(persisted).toHaveLength(7);
      const bindings = persisted.map((fact, index) => ({
        position: index + 1,
        fact_public_id: fact.fact_public_id,
        fact_role: 'general',
        rendered_text: copyLines[index]!,
      }));
      const hook = '7 Moon phase facts worth knowing';
      const cta = 'Follow for more curious space facts.';
      const rendered = content(bindings);
      const payload = {
        ...rendered,
        hook,
        cta,
        body: {
          subject: 'Moon phases',
          facts: bindings.map((binding) => ({
            position: binding.position,
            text: binding.rendered_text,
          })),
        },
        canva_copy: [hook, ...copyLines, cta].join('\n\n'),
        caption: 'Seven facts about the changing appearance of the Moon.',
        hashtags: ['#MoonPhases', '#SpaceFacts', '#NASA'],
        text_metrics: {},
      };
      const snapshot = {
        schema_version: 1,
        module_version: 1,
        config_schema_version: 1,
        content_schema_version: 1,
        renderer_version: 1,
        quality_gate_version: 1,
        editorial_rubric_version: 1,
        source_policy_version: 1,
        dedup_contract_version: 1,
        config_public_id: ctx.data.config_public_id,
        config_updated_at: ctx.data.context_version.config_updated_at,
        fact_count: ctx.data.config.fact_count,
        fact_count_applied: 7,
        fact_count_override: false,
        text_budget: ctx.data.config.text_budget,
        fact_reuse_scope: ctx.data.reuse_policy.scope,
        profile_key: 'fast_trivia',
        render_style: 'plain_lines',
        target_markets: ctx.data.page.target_markets,
        locale: 'en-US',
        line_width_chars: 34,
        target_video_seconds: 13,
        override_reason: null,
      };
      const expr = save(f, {
        key: randomUUID(),
        token,
        configTime: ctx.data.context_version.config_updated_at,
        plan: null,
        schedule: null,
        format: 'single_subject_fast',
        topic: 'nature_science',
        goal: 'follow',
        content: payload,
        generation: snapshot,
        bindings,
        editorial: editorial(),
      } as Parameters<typeof save>[1]);
      const persistedPost = rpc(f, expr) as unknown as {
        data: {
          post: { post_public_id: string; status: string; revision: number; content_hash: string };
        };
      };
      expect(persistedPost.data.post.status).toBe('draft');
      expect(persistedPost.data.post.revision).toBe(1);
      expect(persistedPost.data.post.content_hash).toMatch(/^[0-9a-f]{64}$/);
      // Issue #40: read all eight SQL projections before MCP/Zod. Persist only
      // isolated fixture JSON to the runner's ephemeral temp path (never CI logs).
      const diagnostic: Array<{
        sources: boolean;
        checks: boolean;
        metrics: boolean;
        sqlError?: boolean;
        bytes?: number;
        rpc?: unknown;
      }> = [];
      for (const sources of [false, true]) {
        for (const checks of [false, true]) {
          for (const metrics of [false, true]) {
            try {
              const result = rpc(
                f,
                `api.get_post(1,'${f.workspace}','${persistedPost.data.post.post_public_id}',${sources},${checks},${metrics})`,
              );
              diagnostic.push({
                sources,
                checks,
                metrics,
                bytes: Buffer.byteLength(JSON.stringify(result), 'utf8'),
                rpc: result,
              });
            } catch {
              // Do not output SQL exception text; classify SQL separately.
              diagnostic.push({ sources, checks, metrics, sqlError: true });
            }
          }
        }
      }
      expect(diagnostic).toHaveLength(8);
      const diagnosticPath = process.env.GET_POST_DIFFERENTIAL_FILE;
      if (diagnosticPath) {
        writeFileSync(diagnosticPath, JSON.stringify(diagnostic), { mode: 0o600 });
      }

      const fetched = rpc(
        f,
        `api.get_post(1,'${f.workspace}','${persistedPost.data.post.post_public_id}',true,true,false)`,
      ) as unknown as {
        data: {
          post: {
            status: string;
            revision: number;
            content_hash: string;
            content_payload: { canva_copy: string };
            fact_bindings: { source_snapshot?: { sources: unknown[] } }[];
            system_checks: { overall_status: string };
          };
        };
      };
      expect(fetched.data.post.status).toBe('draft');
      expect(fetched.data.post.content_payload.canva_copy).toBe(payload.canva_copy);
      expect(fetched.data.post.content_hash).toBe(persistedPost.data.post.content_hash);
      expect(fetched.data.post.fact_bindings).toHaveLength(7);
      expect(
        fetched.data.post.fact_bindings.every(
          (binding) => binding.source_snapshot?.sources?.length === 1,
        ),
      ).toBe(true);
      expect(fetched.data.post.system_checks.overall_status).toBe('passed');

    } finally {
      cleanup(f);
    }
  }, 60_000);
});
