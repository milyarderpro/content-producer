// Only local Supabase configuration is read; no keys, JWT or raw responses enter CI logs.
function localAnonKey(): string {
  const result = spawnSync('pnpm', ['exec', 'supabase', 'status', '--output', 'json'], {
    encoding: 'utf8',
    env: { ...process.env, SUPABASE_TELEMETRY_DISABLED: '1' },
  });
  if (result.error || result.status !== 0) throw new Error('LOCAL_SUPABASE_STATUS_FAILED');
  let parsed: Record<string, unknown>;
  try {
    parsed = JSON.parse(result.stdout.slice(result.stdout.indexOf('{'))) as Record<string, unknown>;
  } catch {
    throw new Error('LOCAL_SUPABASE_STATUS_NOT_JSON');
  }
  const key = parsed.ANON_KEY;
  if (typeof key !== 'string' || key.length < 20) throw new Error('LOCAL_ANON_KEY_MISSING');
  return key;
}

function fixtureOwnerJwt(userId: string): string {
  // Read the ephemeral local Auth signing secret without logging or persisting it.
  // A direct password grant cannot supply the required OAuth client_id claim.
  const result = spawnSync('docker', ['inspect', 'supabase_auth_content-producer'], {
    encoding: 'utf8',
  });
  if (result.error || result.status !== 0) {
    throw new Error('LOCAL_AUTH_CONTAINER_NOT_FOUND');
  }
  let env: string[];
  try {
    const container = JSON.parse(result.stdout) as Array<{ Config?: { Env?: string[] } }>;
    env = container[0]?.Config?.Env ?? [];
  } catch {
    throw new Error('LOCAL_AUTH_CONTAINER_INFO_INVALID');
  }
  const entry = env.find((value) => value.startsWith('GOTRUE_JWT_SECRET='));
  const secret = entry?.slice('GOTRUE_JWT_SECRET='.length);
  if (!secret || secret.length < 20) throw new Error('LOCAL_SIGNING_KEY_UNAVAILABLE');
  const now = Math.floor(Date.now() / 1000);
  const encode = (value: object) => Buffer.from(JSON.stringify(value)).toString('base64url');
  const unsigned =
    encode({ alg: 'HS256', typ: 'JWT' }) +
    '.' +
    encode({
      sub: userId,
      role: 'authenticated',
      client_id: randomUUID(),
      aud: 'authenticated',
      iss: 'http://127.0.0.1:54321/auth/v1',
      iat: now,
      exp: now + 600,
    });
  return unsigned + '.' + createHmac('sha256', secret).update(unsigned).digest('base64url');
}

async function postgrestGetPost(
  anonKey: string,
  jwt: string,
  workspace: string,
  postId: string,
  sources: boolean,
  checks: boolean,
  metrics: boolean,
): Promise<{ status: number; bytes: number; jsonValid: boolean; rpc?: unknown }> {
  const response = await fetch('http://127.0.0.1:54321/rest/v1/rpc/get_post', {
    method: 'POST',
    redirect: 'error',
    signal: AbortSignal.timeout(10000),
    headers: {
      apikey: anonKey,
      Authorization: 'Bearer ' + jwt,
      'Content-Type': 'application/json',
      'Accept-Profile': 'api',
      'Content-Profile': 'api',
    },
    body: JSON.stringify({
      p_request_schema_version: 1,
      p_workspace_public_id: workspace,
      p_post_public_id: postId,
      p_include_sources: sources,
      p_include_checks: checks,
      p_include_latest_metrics: metrics,
    }),
  });
  const body = await response.text();
  const bytes = Buffer.byteLength(body, 'utf8');
  let rpc: unknown;
  let jsonValid = false;
  try {
    rpc = JSON.parse(body);
    jsonValid = true;
  } catch {
    // Keep only status/size/classification; never log the raw body.
  }
  return { status: response.status, bytes, jsonValid, ...(response.ok ? { rpc } : {}) };
}

// Distinct, synthetic source evidence variants modeled on the LIVE risk shapes.
// Keep the original missing-date normalization test unchanged.
function mixedSourceEvidence(position: number) {
  const primary = sourceWithoutOptionalDates(position);
  const sources = [position <= 4 ? { ...primary, updated_at: '2026-09-22' } : primary];
  if (position === 2 || position === 6) {
    const additional = sourceWithoutOptionalDates(3);
    sources.push({
      ...additional,
      url: 'https://science.nasa.gov/moon/moon-facts/',
      canonical_url: 'https://science.nasa.gov/moon/moon-facts/',
      title: 'Moon Facts',
      updated_at: '2026-10-01',
    });
  }
  return sources;
}

function structuredNumbers(index: number) {
  if (index === 0) return [{ value: '8', unit: null, role: 'phase_count' }];
  if (index === 1) return [{ value: '29.5', unit: 'days', role: 'cycle_duration' }];
  if (index === 4) return [{ value: '1', unit: null, role: 'quarter_sequence' }];
  return [];
}

